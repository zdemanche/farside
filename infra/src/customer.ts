import { readFileSync } from "node:fs";
import { type AccountRegistry, assertDedicatedAccount } from "./account.js";
import { PRODUCT_KEY, customerAddress } from "./product.js";
import type { FarsideTagInput } from "./tags.js";

/** Per-customer deploy parameters, keyed by tenant slug (infra/customers.json). Account ids stay in accounts.json. */
export type CustomerParams = {
  environment: FarsideTagInput["environment"];
  region: string;
  logRetentionDays?: number;
};

export type CustomerCatalogue = Record<string, CustomerParams>;

export type CustomerStack = {
  customerName: string;
  accountId: string;
  address: string;
  region: string;
  /** Fully qualified stack name on the S3 backend. */
  stackName: string;
  /** Short name; Pulumi reads Pulumi.<stackFile>.yaml. */
  stackFile: string;
  config: Record<string, string>;
};

const ENVIRONMENTS = ["dev", "non-prod", "prod", "prod-critical"] as const;
const REGION = /^[a-z]{2}(-[a-z]+)+-\d$/;

export function parseCustomerCatalogue(raw: string): CustomerCatalogue {
  const parsed = JSON.parse(raw) as unknown;
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new Error("customer catalogue must be an object keyed by tenant slug");
  }
  const catalogue: CustomerCatalogue = {};
  for (const [slug, value] of Object.entries(parsed as Record<string, unknown>)) {
    customerAddress(slug);
    const params = value as Partial<CustomerParams>;
    if (!ENVIRONMENTS.includes(params.environment as CustomerParams["environment"])) {
      throw new Error(`customer ${slug}: environment must be one of ${ENVIRONMENTS.join(", ")}`);
    }
    if (typeof params.region !== "string" || !REGION.test(params.region)) {
      throw new Error(`customer ${slug}: region must be an AWS region such as us-east-2`);
    }
    if (params.logRetentionDays !== undefined && (!Number.isInteger(params.logRetentionDays) || params.logRetentionDays < 1)) {
      throw new Error(`customer ${slug}: logRetentionDays must be a positive integer`);
    }
    catalogue[slug] = {
      environment: params.environment as CustomerParams["environment"],
      region: params.region,
      ...(params.logRetentionDays === undefined ? {} : { logRetentionDays: params.logRetentionDays }),
    };
  }
  return catalogue;
}

export function loadCustomerCatalogue(path: string): CustomerCatalogue {
  return parseCustomerCatalogue(readFileSync(path, "utf8"));
}

/**
 * Stack config for one customer. The account id must be the one registered to the
 * slug (same guard as the Pulumi program, with the caller assumed to be that account).
 * The operator token is not here: the workflow sets it as a stack secret.
 */
export function customerStack(
  customerName: string,
  accountId: string,
  catalogue: CustomerCatalogue,
  registry: AccountRegistry,
): CustomerStack {
  const address = customerAddress(customerName);
  assertDedicatedAccount(accountId, accountId, customerName, registry);
  const params = Object.hasOwn(catalogue, customerName) ? catalogue[customerName] : undefined;
  if (!params) {
    throw new Error(`customer ${customerName} has no entry in infra/customers.json`);
  }
  const config: Record<string, string> = {
    "aws:region": params.region,
    "farside:customerName": customerName,
    "farside:accountId": accountId,
    "farside:environment": params.environment,
    "farside:address": address,
  };
  if (params.logRetentionDays !== undefined) {
    config["farside:logRetentionDays"] = String(params.logRetentionDays);
  }
  return {
    customerName,
    accountId,
    address,
    region: params.region,
    stackName: `organization/${PRODUCT_KEY}/${customerName}`,
    stackFile: customerName,
    config,
  };
}

/** Pulumi.<customer>.yaml body. Values are quoted so account ids stay strings. */
export function renderStackYaml(stack: CustomerStack): string {
  const lines = Object.entries(stack.config).map(([key, value]) => `  ${key}: ${JSON.stringify(value)}`);
  return `# Generated by infra/src/customer-cli.ts for ${stack.customerName}. Do not hand-edit.\nconfig:\n${lines.join("\n")}\n`;
}
